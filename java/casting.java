public class casting {
    public static void main(String[] args){

        //casting
        // implicit casting
        double price = 100.00;
        double finalPrice = price + 18;

        System.out.println(finalPrice);

        //explicit casting

        int p = 200;
        int fP = p +(int) 18.98;
        System.out.println(fP);

        // In explicit casting deciimal number does not show


   //CONSTANT'S

       int age = 20;
       age = 21;
       age = 22;

       final float PI=3.14F;
       //in code Constant always Capital latter, like PI

       System.out.println(age);
       System.out.println(PI);
    }
}
